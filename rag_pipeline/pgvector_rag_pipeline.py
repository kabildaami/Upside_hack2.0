def create_openrouter_client() -> OpenAI:
    api_key = os.getenv("OPENROUTER_API_KEY")
    if not api_key:
        raise ValueError("OPENROUTER_API_KEY is missing from environment / .env")

    base_url = os.getenv("OPENROUTER_BASE_URL", "https://openrouter.ai/api/v1")
    default_headers: Dict[str, str] = {}
    if os.getenv("OPENROUTER_SITE_URL"):
        default_headers["HTTP-Referer"] = os.getenv("OPENROUTER_SITE_URL", "")
    if os.getenv("OPENROUTER_APP_NAME"):
        default_headers["X-Title"] = os.getenv("OPENROUTER_APP_NAME", "")

    return OpenAI(
        api_key=api_key,
        base_url=base_url,
        default_headers=default_headers or None,
    )


def create_embedding_provider(openrouter_client: Optional[OpenAI] = None) -> EmbeddingProvider:
    backend = os.getenv("EMBEDDING_BACKEND", "local").strip().lower()
    model_name = os.getenv("NOMIC_EMBEDDING_MODEL", "nomic-ai/nomic-embed-text-v1.5").strip()

    if backend == "openrouter":
        client = openrouter_client or create_openrouter_client()
        return OpenRouterEmbeddingProvider(client=client, model=model_name)

    return LocalNomicEmbeddingProvider(model_name=model_name)


