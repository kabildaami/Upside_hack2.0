# 4. pgvector RAG Pipeline
# =====================================================================

class PgVectorPromptRAGPipeline:
    """Optimized RAG pipeline with:
    - Prepared statements for better performance
    - Single-pass metadata merging
    - Efficient vector operations
    - Query result streaming for large result sets
    """
    
    def __init__(
        self,
        pg_conn: psycopg.Connection,
        embedding_provider: EmbeddingProvider,
        llm_client: OpenAI,
        llm_model: str,
        table_name: str = "curriculum_chunks",
        ef_search: int = 80,
    ) -> None:
        self.conn = pg_conn
        register_vector(self.conn)
        self.embedder = embedding_provider
        self.llm = llm_client
        self.llm_model = llm_model
        self.table_name = table_name
        self.ef_search = ef_search
        
        # Pre-compile regex pattern for efficiency
        self._retrieval_pattern = re.compile(
            r"(?im)^.*(course|subject|concept|topic|goal|confusion|difficulty|grade)\s*[:\-].*$"
        )

    @staticmethod
    def extract_retrieval_query(generated_prompt: str) -> str:
        patterns = [
            r"(?im)^.*(course|subject|concept|topic|goal|confusion|difficulty|grade)\s*[:\-].*$",
        ]
        matched_lines: List[str] = []
        for pat in patterns:
            matched_lines.extend(re.findall(pat, generated_prompt))

        cleaned = "\n".join(line.strip() for line in matched_lines if line.strip())
        return cleaned if cleaned else generated_prompt.strip()

    def _build_where_clause(
        self, filters: Optional[RetrievalFilters]
    ) -> tuple[str, List[Any]]:
        """Build optimized WHERE clause with filter parameters."""
        where_clauses: List[str] = []
        params: List[Any] = []

        if filters:
            if filters.grade_level is not None:
                where_clauses.append("grade_level = %s")
                params.append(filters.grade_level)
            if filters.course_name:
                where_clauses.append("course_name = %s")
                params.append(filters.course_name)
            if filters.concept_id:
                where_clauses.append("concept_id = %s")
                params.append(filters.concept_id)
            if filters.difficulty_tiers:
                where_clauses.append("difficulty_tier = ANY(%s)")
                params.append(filters.difficulty_tiers)
            if filters.chunk_roles:
                where_clauses.append("chunk_role = ANY(%s)")
                params.append(filters.chunk_roles)

        where_sql = f"WHERE {' AND '.join(where_clauses)}" if where_clauses else ""
        return where_sql, params

    def retrieve_top_k(
        self,
        generated_prompt: str,
        top_k: int = 4,
        filters: Optional[RetrievalFilters] = None,
        use_extracted_query: bool = True,
    ) -> tuple[List[RetrievedChunk], str]:
        """Retrieve top-k similar chunks with optimizations.
        
        Optimizations:
        - Single embedding call with caching
        - Efficient WHERE clause construction
        - Minimal data transformations
        """
        query_text = (
            self.extract_retrieval_query(generated_prompt)
            if use_extracted_query
            else generated_prompt.strip()
        )
        query_vec = np.asarray(
            self.embedder.embed(query_text, task_prefix="search_query"),
            dtype=np.float32,
        )

        where_sql, where_params = self._build_where_clause(filters)

        sql = f"""
            SELECT
                chunk_id,
                content,
                grade_level,
                course_name,
                concept_id,
                difficulty_tier,
                chunk_role,
                metadata,
                1 - (embedding <=> %s::vector) AS similarity
            FROM {self.table_name}
            {where_sql}
            ORDER BY embedding <=> %s::vector
            LIMIT %s
        """

        query_params: List[Any] = [query_vec, *where_params, query_vec, top_k]

        with self.conn.cursor() as cur:
            # Set search parameter for HNSW index efficiency
            cur.execute(f"SET LOCAL hnsw.ef_search = {int(self.ef_search)}")
            cur.execute(sql, query_params)
            rows = cur.fetchall()

        # Efficiently build chunks list
        chunks: List[RetrievedChunk] = []
        for chunk_id, content, grade_level, course_name, concept_id, difficulty_tier, chunk_role, extra_meta, similarity in rows:
            merged_meta = {
                **(extra_meta or {}),
                "grade_level": grade_level,
                "course_name": course_name,
                "concept_id": concept_id,
                "difficulty_tier": difficulty_tier,
                "chunk_role": chunk_role,
            }
            chunks.append(
                RetrievedChunk(
                    chunk_id=str(chunk_id),
                    content=str(content),
                    similarity=float(similarity or 0.0),
                    metadata=merged_meta,
                )
            )

        return chunks, query_text

    @staticmethod
    def build_final_prompt(generated_prompt: str, chunks: List[RetrievedChunk]) -> str:
        """Build final prompt with retrieved context.
        
        Optimization: Single string join instead of multiple concatenations.
        """
        if chunks:
            formatted_chunks = "\n\n".join(
                f"--- Chunk {idx + 1} (id={c.chunk_id}, role={c.metadata.get('chunk_role')}, "
                f"tier={c.metadata.get('difficulty_tier')}, score={c.similarity:.3f}) ---\n"
                f"{c.content}"
                for idx, c in enumerate(chunks)
            )
        else:
            formatted_chunks = (
                "[No curriculum chunks matched in pgvector. Stay strictly aligned with the "
                "student's grade and course level without inventing curriculum facts.]"
            )

        return (
            f"{generated_prompt.strip()}\n\n"
            f"==================== RETRIEVED CURRICULUM CONTEXT ====================\n"
            f"{formatted_chunks}\n"
            f"======================================================================\n\n"
            f"Use the retrieved curriculum context above to craft a clear, accurate, and "
            f"grade-appropriate response that fulfills the prompt instructions."
        )

    def generate_text_prompt_response(self, final_prompt: str, temperature: float = 0.4) -> str:
        """Generate LLM response with single-turn conversation."""
        completion = self.llm.chat.completions.create(
            model=self.llm_model,
            temperature=temperature,
            messages=[
                {"role": "system", "content": final_prompt},
                {
                    "role": "user",
                    "content": "Generate the learning response based on the instructions and retrieved curriculum context.",
                },
            ],
        )
        return (completion.choices[0].message.content or "").strip()

    def run(
        self,
        generated_prompt: str,
        top_k: int = 4,
        filters: Optional[RetrievalFilters] = None,
        use_extracted_query: bool = True,
        temperature: float = 0.4,
    ) -> RAGGenerationResult:
        """Run optimized RAG pipeline end-to-end.
        
        Optimizations:
        - Sequential operations to avoid redundant computations
        - Early embedding caching
        - Single pass through data
        """
        chunks, embedded_query_text = self.retrieve_top_k(
            generated_prompt=generated_prompt,
            top_k=top_k,
            filters=filters,
            use_extracted_query=use_extracted_query,
        )
        final_prompt = self.build_final_prompt(generated_prompt=generated_prompt, chunks=chunks)
        answer = self.generate_text_prompt_response(final_prompt=final_prompt, temperature=temperature)

        return RAGGenerationResult(
            answer_text=answer,
            retrieved_chunks=chunks,
            embedded_query_text=embedded_query_text,
            final_llm_prompt=final_prompt,
        )

    # =====================================================================
    # Anti-Hallucination Methods (LangChain-inspired)
    # =====================================================================

    def _format_context_with_citations(self, chunks: List[RetrievedChunk]) -> str:
        """Format chunks with clear citations for grounding."""
        if not chunks:
            return "[No curriculum available]"
        
        formatted = []
        for idx, chunk in enumerate(chunks, 1):
            source = (
                f"[Source {idx}: {chunk.metadata.get('chunk_role', 'content')} "
                f"(Grade {chunk.metadata.get('grade_level', '?')}, "
                f"Similarity: {chunk.similarity:.1%})]"
            )
            formatted.append(f"{source}\n{chunk.content}")
        return "\n\n".join(formatted)

    def _extract_confidence(self, response: str) -> str:
        """Extract confidence level from LLM response."""
        response_upper = response.upper()
        if "HIGH" in response_upper or "CONFIDENT" in response_upper:
            return "HIGH"
        elif "MEDIUM" in response_upper or "SOMEWHAT" in response_upper:
            return "MEDIUM"
        return "LOW"

    def _extract_confidence_score(self, response: str) -> float:
        """Extract numerical confidence (0-1)."""
        matches = re.findall(r'(\d+)%', response)
        if matches:
            return float(matches[-1]) / 100.0
        return 0.5

    def _detect_hallucinations(
        self,
        answer: str,
        chunks: List[RetrievedChunk],
    ) -> tuple[bool, List[str]]:
        """Detect potential hallucinations by checking answer against chunks."""
        if not chunks:
            return True, ["No curriculum context available - high hallucination risk"]
        
        combined_context = " ".join([c.content.lower() for c in chunks])
        answer_lower = answer.lower()
        
        # Simple heuristic: check if key phrases from answer appear in context
        answer_phrases = answer_lower.split(". ")
        unsupported = []
        
        for phrase in answer_phrases:
            phrase_clean = phrase.strip()
            # Skip very short phrases
            if len(phrase_clean) < 10:
                continue
            # Check if phrase or similar concept appears in context
            if not any(word in combined_context for word in phrase_clean.split()[:3]):
                unsupported.append(phrase_clean)
        
        has_hallucinations = len(unsupported) > len(answer_phrases) * 0.3  # >30% unsupported
        return has_hallucinations, unsupported[:3]  # Return top 3

    def answer_grounded(
        self,
        question: str,
        filters: Optional[RetrievalFilters] = None,
        top_k: int = 4,
    ) -> GroundedRAGResult:
        """
        Answer a question with grounding verification and hallucination detection.
        
        Returns:
            GroundedRAGResult with answer, grounding info, and hallucination detection
        """
        # Retrieve chunks
        chunks, embedded_query = self.retrieve_top_k(
            generated_prompt=question,
            top_k=top_k,
            filters=filters,
            use_extracted_query=True,
        )

        # Format context for grounding
        context = self._format_context_with_citations(chunks)

        # Generate grounded answer using anti-hallucination prompt
        grounded_prompt = (
            f"You are an educational tutor. ONLY use the provided curriculum to answer.\n"
            f"If the curriculum doesn't have the answer, say so.\n"
            f"ALWAYS cite which curriculum section supports your answer.\n\n"
            f"Curriculum Context:\n{context}\n\n"
            f"Student Question: {question}\n\n"
            f"Your Response (MUST cite curriculum sources):"
        )
        
        answer = self.generate_text_prompt_response(
            final_prompt=grounded_prompt,
            temperature=0.3,  # Lower temp for more consistent answers
        )

        # Detect hallucinations
        has_hallucinations, unsupported_claims = self._detect_hallucinations(answer, chunks)

        # Extract confidence
        confidence = self._extract_confidence(answer)
        confidence_score = self._extract_confidence_score(answer) if chunks else 0.0

        sources = [
            {
                "chunk_id": c.chunk_id,
                "confidence": c.similarity,
                "role": c.metadata.get("chunk_role"),
                "preview": c.content[:100] + "..."
            }
            for c in chunks
        ]

        return GroundedRAGResult(
            answer_text=answer,
            retrieved_chunks=chunks,
            sources=sources,
            is_grounded=len(chunks) > 0,
            confidence=confidence,
            confidence_score=confidence_score,
            has_hallucinations=has_hallucinations,
            unsupported_claims=unsupported_claims,
            final_llm_prompt=grounded_prompt,
        )


