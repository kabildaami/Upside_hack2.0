from openai import OpenAI
from pgvector.psycopg import register_vector


# =====================================================================
# 1. Data Models
# =====================================================================

@dataclass
class RetrievalFilters:
    grade_level: Optional[int] = None
    course_name: Optional[str] = None
    concept_id: Optional[str] = None
    difficulty_tiers: Optional[List[str]] = None
    chunk_roles: Optional[List[str]] = None


@dataclass
class RetrievedChunk:
    chunk_id: str
    content: str
    similarity: float
    metadata: Dict[str, Any] = field(default_factory=dict)


@dataclass
class RAGGenerationResult:
    answer_text: str
    retrieved_chunks: List[RetrievedChunk]
    embedded_query_text: str
    final_llm_prompt: str


@dataclass
class GroundedRAGResult:
    """Enhanced result with grounding verification and hallucination detection."""
    answer_text: str
    retrieved_chunks: List[RetrievedChunk]
    sources: List[Dict[str, Any]]
    is_grounded: bool
    confidence: str  # HIGH, MEDIUM, LOW
    confidence_score: float  # 0-1
    has_hallucinations: bool
    unsupported_claims: List[str]
    final_llm_prompt: str


