# 2. Embedding Providers (Nomic Local or OpenRouter)
# =====================================================================

class EmbeddingProvider(ABC):
    @abstractmethod
    def embed(self, text: str, task_prefix: str = "search_query") -> List[float]:
        raise NotImplementedError


class LocalNomicEmbeddingProvider(EmbeddingProvider):
    """
    Uses `sentence-transformers` with `nomic-ai/nomic-embed-text-v1.5`.
    Nomic v1.5 recommends task prefixes such as 'search_query: ' or 'search_document: '.
    
    Optimizations:
    - Lazy model loading on first use
    - LRU cache for embeddings to avoid duplicate computations
    - Batch encoding support for multiple texts
    """

    def __init__(
        self,
        model_name: str = "nomic-ai/nomic-embed-text-v1.5",
        trust_remote_code: bool = True,
        cache_size: int = 128,
    ) -> None:
        self.model_name = model_name
        self.trust_remote_code = trust_remote_code
        self._model = None
        self.cache_size = cache_size

    @property
    def model(self):
        """Lazy load model on first use."""
        if self._model is None:
            from sentence_transformers import SentenceTransformer
            self._model = SentenceTransformer(
                self.model_name, trust_remote_code=self.trust_remote_code
            )
        return self._model

    def _get_cache_key(self, text: str, task_prefix: str) -> str:
        """Generate cache key for embedding."""
        content = f"{task_prefix}:{text}"
        return hashlib.md5(content.encode()).hexdigest()

    @lru_cache(maxsize=128)
    def _cached_embed(self, cache_key: str, prefixed_text: str) -> tuple:
        """Cache wrapper for embeddings."""
        vec = self.model.encode(prefixed_text, normalize_embeddings=True)
        return tuple(vec)

    def embed(self, text: str, task_prefix: str = "search_query") -> List[float]:
        prefixed_text = f"{task_prefix}: {text}" if task_prefix else text
        cache_key = self._get_cache_key(text, task_prefix)
        cached_vec = self._cached_embed(cache_key, prefixed_text)
        return list(cached_vec)

    def embed_batch(self, texts: List[str], task_prefix: str = "search_query") -> List[List[float]]:
        """Efficiently encode multiple texts."""
        prefixed_texts = [f"{task_prefix}: {t}" if task_prefix else t for t in texts]
        vecs = self.model.encode(prefixed_texts, normalize_embeddings=True)
        return [vec.tolist() for vec in vecs]


class OpenRouterEmbeddingProvider(EmbeddingProvider):
    """Calls an embeddings endpoint through the OpenRouter-compatible client.
    
    Optimizations:
    - Batch embedding support to reduce API calls
    - LRU cache for identical embeddings
    """

    def __init__(
        self,
        client: OpenAI,
        model: str = "nomic-ai/nomic-embed-text-v1-5",
    ) -> None:
        self.client = client
        self.model_name = model

    def _get_cache_key(self, text: str, task_prefix: str) -> str:
        """Generate cache key for embedding."""
        content = f"{task_prefix}:{text}"
        return hashlib.md5(content.encode()).hexdigest()

    @lru_cache(maxsize=256)
    def _cached_embed(self, cache_key: str, prefixed_text: str) -> tuple:
        """Cache wrapper for API embeddings."""
        resp = self.client.embeddings.create(model=self.model_name, input=prefixed_text)
        return tuple(resp.data[0].embedding)

    def embed(self, text: str, task_prefix: str = "search_query") -> List[float]:
        prefixed_text = f"{task_prefix}: {text}" if task_prefix else text
        cache_key = self._get_cache_key(text, task_prefix)
        cached_vec = self._cached_embed(cache_key, prefixed_text)
        return list(cached_vec)

    def embed_batch(self, texts: List[str], task_prefix: str = "search_query") -> List[List[float]]:
        """Efficiently encode multiple texts in a single API call."""
        prefixed_texts = [f"{task_prefix}: {t}" if task_prefix else t for t in texts]
        resp = self.client.embeddings.create(model=self.model_name, input=prefixed_texts)
        return [item.embedding for item in resp.data]


