"""
pgvector_rag_pipeline.py

Loads configuration from .env, accepts a prompt string generated by another file,
embeds it with Nomic, retrieves top-k similar chunks from PostgreSQL via pgvector,
assembles the grounded prompt, and generates the response via OpenRouter.

Optimizations:
- Embedding caching to avoid duplicate embeddings
- Batch embedding for multiple queries
- Optimized PostgreSQL queries with index utilization
- Lazy loading of embedding models

Anti-Hallucination Features (LangChain-inspired):
- Grounded prompting that enforces curriculum alignment
- Source attribution and verification
- Confidence scoring
- Structured output with hallucination detection
"""

from __future__ import annotations

import hashlib
import os
import re
from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from functools import lru_cache
from typing import Any, Dict, List, Optional

